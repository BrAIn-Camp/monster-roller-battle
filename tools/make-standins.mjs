// Regenerates STANDINS.md from the critter files and critters/slots.json.   node tools/make-standins.mjs
// Run it whenever a critter is added, renamed or changed.
import { readFileSync, writeFileSync } from 'node:fs';
import a from '../critters/critters_1.js';
import b from '../critters/critters_2.js';
import c from '../critters/critters_3.js';
const slots = JSON.parse(readFileSync(new URL('../critters/slots.json', import.meta.url), 'utf8'));
const all = [...a, ...b, ...c].sort((x, y) => x.dex - y.dex);
const cap = (s) => s[0].toUpperCase() + s.slice(1);
let md = `# Stand-in reference

Generated by \`tools/make-standins.mjs\` from \`critters/critters_*.js\` and \`critters/slots.json\`. Do not edit by hand; re-run the script after any change to the critters.

Each of the 151 slots has an original critter that shares three things with its counterpart: the species category, the types and the Pokédex height (taken from the open PokéAPI data set; Fairy and Steel are dropped because they did not exist in the first 151). Names and designs are original and deliberately different.

Size is the critter's longest side. The ball can roll a critter up once the ball is 2.5 times that wide.

| # | Stand-in | Species | Types | Height | Counterpart | Lives in | How common | Moves | Temper |
|---|---|---|---|---|---|---|---|---|---|
`;
for (const k of all) {
  const s = slots.find((x) => x.dex === k.dex);
  md += `| ${String(k.dex).padStart(3, '0')} | ${k.name} | ${k.species} | ${k.types.map(cap).join(' / ')} | ${k.height} m | ${s.official} | ${k.habitat} | ${k.rarity} | ${k.move} | ${k.temper} |\n`;
}
md += `
## Other stand-ins

| Stand-in | Closest official thing |
|---|---|
| The striped orb | Poké Ball |
| The trainer (fixed 1.5 m tall) | Player character |
| Tonic Bottle | Potion |
| Berry | Oran Berry and similar |
| Critter dex | Pokédex |
| Saltmere Island | A self-contained island region |

## Size note

Only four of the 151 are over 2.5 m (3.5 m, 4.0 m, 6.5 m and 8.8 m), so a ball of about 6 m can roll up almost every critter.
Growth beyond that comes from scenery: boats, sheds, trees and houses.
`;
writeFileSync(new URL('../STANDINS.md', import.meta.url), md);
console.log('wrote STANDINS.md with', all.length, 'critters');
